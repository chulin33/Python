#这一天，小鱼给自己的游泳时间做了精确的计时（本题中的计时都按 24 小时制计算），它发现自己从 a 时 b 分一直游泳到当天的 c 时 d 分，请你帮小鱼计算一下，它这天一共游了多少时间呢？
#输入格式:一行内输入四个整数，以空格隔开，分别表示题目中的 a,b,c,d。
#输出格式:一行内输出两个整数 e 和 f，用空格间隔，依次表示小鱼这天一共游了多少小时多少分钟。其中表示分钟的整数 f 应该小于 60。
a,b,c,d=map(int,input().split())
if d<b:
    f=d+60-b
    e=c-a-1
else:
    f=d-b
    e=c-a
print(f"{e} {f}")

#最简答案
a, b, c, d = map(int, input().split())
if d < b:
    c -= 1
    d += 60
print(c - a, d - b)
